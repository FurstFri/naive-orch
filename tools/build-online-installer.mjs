#!/usr/bin/env node

// Build a single text-only installer that can be piped directly to /bin/sh on
// OpenWrt. Keeping the payload as quoted heredocs avoids requiring base64,
// unzip, git or tar before the real installer can install dependencies.

import { promises as fs } from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(projectRoot, 'install-online.sh');

async function walk(directory) {
	const entries = await fs.readdir(directory, { withFileTypes: true });
	const files = [];

	for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
		const fullPath = path.join(directory, entry.name);
		if (entry.isDirectory())
			files.push(...await walk(fullPath));
		else if (entry.isFile())
			files.push(fullPath);
	}

	return files;
}

function shellQuote(value) {
	return `'${value.replaceAll("'", `'"'"'`)}'`;
}

function installMode(relativePath) {
	if (relativePath === 'install.sh' || relativePath === 'root/etc/init.d/naive-orch')
		return '0755';
	if (relativePath.startsWith('root/usr/libexec/naive-orch/') && !relativePath.endsWith('/lib.sh'))
		return '0755';
	return '0644';
}

const payloadFiles = [
	path.join(projectRoot, 'install.sh'),
	...await walk(path.join(projectRoot, 'root'))
];

const output = [
	'#!/bin/sh',
	'# Generated by tools/build-online-installer.mjs; do not edit by hand.',
	'# Usage: wget -qO- https://host/install-online.sh | sh',
	'',
	'set -eu',
	'',
	'BUNDLE_DIR="$(mktemp -d /tmp/naive-orch-install.XXXXXX)"',
	'cleanup_bundle() { rm -rf "$BUNDLE_DIR"; }',
	"trap cleanup_bundle 0",
	"trap 'exit 1' 1 2 15",
	'',
	'extract_file() {',
	'\tlocal relative="$1" mode="$2" target="$BUNDLE_DIR/$1"',
	'\tmkdir -p "$(dirname "$target")"',
	'\tcat > "$target"',
	'\tchmod "$mode" "$target"',
	'}',
	''
];

for (let index = 0; index < payloadFiles.length; index++) {
	const filePath = payloadFiles[index];
	const relativePath = path.relative(projectRoot, filePath).split(path.sep).join('/');
	const marker = `__NAIVE_ORCH_FILE_${index}__`;
	let contents = await fs.readFile(filePath, 'utf8');
	contents = contents.replaceAll('\r\n', '\n');
	if (!contents.endsWith('\n'))
		contents += '\n';
	if (contents.includes(marker))
		throw new Error(`Heredoc marker collision in ${relativePath}`);

	output.push(
		`extract_file ${shellQuote(relativePath)} ${shellQuote(installMode(relativePath))} <<'${marker}'`,
		contents.slice(0, -1),
		marker,
		''
	);
}

output.push(
	'cd "$BUNDLE_DIR"',
	'sh ./install.sh --enable "$@"',
	''
);

await fs.writeFile(outputPath, output.join('\n'), { mode: 0o755 });
process.stdout.write(`Built ${outputPath} with ${payloadFiles.length} files\n`);
